import * as fs from 'node:fs/promises';
import * as path from 'node:path';

const integrationDirectory = '.valdroid';
const entryName = 'react-scan-entry.js';
const manifestName = 'react-scan.json';

interface PackageJSON {
	main?: unknown;
	dependencies?: Record<string, string>;
	devDependencies?: Record<string, string>;
	[key: string]: unknown;
}

interface IntegrationManifest {
	version: 1;
	previousMain?: string;
}

export interface ReactScanProject {
	root: string;
	packagePath: string;
	packageJSON: PackageJSON;
	originalMain?: string;
	entryModule: string;
	hasReactScan: boolean;
	enabled: boolean;
}

export class ReactScanIntegration {
	static async inspect(root: string): Promise<ReactScanProject> {
		const packagePath = path.join(root, 'package.json');
		let packageJSON: PackageJSON;
		try {packageJSON = JSON.parse(await fs.readFile(packagePath, 'utf8')) as PackageJSON;} catch (error) {
			throw new Error(`Could not read ${packagePath}: ${error instanceof Error ? error.message : String(error)}`);
		}
		if (!hasDependency(packageJSON, 'expo')) {throw new Error('React Scan setup currently supports Expo projects only. No Expo dependency was found.');}
		const originalMain = typeof packageJSON.main === 'string' ? packageJSON.main : undefined;
		const entryModule = originalMain ?? 'expo/AppEntry';
		const generatedEntry = `./${integrationDirectory}/${entryName}`;
		return {root, packagePath, packageJSON, originalMain, entryModule, hasReactScan: hasDependency(packageJSON, 'react-scan'), enabled: entryModule === generatedEntry};
	}

	static async enable(project: ReactScanProject, runtimePath?: string, controlURL?: string): Promise<void> {
		const directory = path.join(project.root, integrationDirectory);
		await fs.mkdir(directory, {recursive: true});
		if (!project.enabled) {
			for (const name of [entryName, manifestName, 'react-scan-runtime.js']) {
				if (await fs.stat(path.join(directory, name)).then(() => true, () => false)) {throw new Error(`Refusing to overwrite existing ${integrationDirectory}/${name}.`);}
			}
		}
		const previousMain = project.enabled ? await readManifest(directory).then(manifest => manifest.previousMain) : project.originalMain;
		if (runtimePath) {await fs.copyFile(runtimePath, path.join(directory, 'react-scan-runtime.js'));}
		await fs.writeFile(path.join(directory, entryName), entrySource(project.root, previousMain ?? 'expo/AppEntry', Boolean(runtimePath), controlURL), 'utf8');
		await fs.writeFile(path.join(directory, manifestName), `${JSON.stringify({version: 1, previousMain} satisfies IntegrationManifest, undefined, 2)}\n`, 'utf8');
		if (!project.enabled) {
			await writePackage(project.packagePath, {...project.packageJSON, main: `./${integrationDirectory}/${entryName}`});
		}
	}

	static async disable(project: ReactScanProject): Promise<void> {
		if (!project.enabled) {return;}
		const directory = path.join(project.root, integrationDirectory);
		const manifest = await readManifest(directory);
		const next = {...project.packageJSON};
		if (manifest.previousMain === undefined) {delete next.main;}
		else {next.main = manifest.previousMain;}
		await writePackage(project.packagePath, next);
		await Promise.all([
			fs.rm(path.join(directory, entryName), {force: true}),
			fs.rm(path.join(directory, manifestName), {force: true}),
			fs.rm(path.join(directory, 'react-scan-runtime.js'), {force: true}),
		]);
		await fs.rmdir(directory).catch(() => undefined);
	}
}

function hasDependency(packageJSON: PackageJSON, name: string): boolean {
	return Boolean(packageJSON.dependencies?.[name] || packageJSON.devDependencies?.[name]);
}

async function readManifest(directory: string): Promise<IntegrationManifest> {
	try {
		const manifest = JSON.parse(await fs.readFile(path.join(directory, manifestName), 'utf8')) as IntegrationManifest;
		if (manifest.version !== 1 || (manifest.previousMain !== undefined && typeof manifest.previousMain !== 'string')) {throw new Error('invalid manifest');}
		return manifest;
	} catch (error) {
		throw new Error(`React Scan integration is enabled but its manifest is unavailable: ${error instanceof Error ? error.message : String(error)}`);
	}
}

async function writePackage(packagePath: string, packageJSON: PackageJSON): Promise<void> {
	await fs.writeFile(packagePath, `${JSON.stringify(packageJSON, undefined, 2)}\n`, 'utf8');
}

function entrySource(projectRoot: string, entryModule: string, bundled = false, controlURL?: string): string {
	const entry = projectEntrySpecifier(projectRoot, entryModule);
	return `/* Generated by Valdroid. Development-only React Scan bootstrap. */
if (__DEV__) {
  try {
    ${bundled && controlURL ? `require('./react-scan-runtime').startScan(${JSON.stringify(controlURL)});` : '/* Runtime supplied when launched by Valdroid. */'}
  } catch (error) {
    console.warn('[Valdroid React Scan] failed to initialize', error);
  }
}
require(${JSON.stringify(entry)});
`;
}

function projectEntrySpecifier(projectRoot: string, entryModule: string): string {
	if (!entryModule.startsWith('.') && !entryModule.endsWith('.js') && !entryModule.endsWith('.cjs') && !entryModule.endsWith('.ts') && !entryModule.endsWith('.tsx')) {return entryModule;}
	const resolved = path.resolve(projectRoot, entryModule);
	const relative = path.relative(path.join(projectRoot, integrationDirectory), resolved);
	return relative.startsWith('.') ? relative : `./${relative}`;
}
